#!/usr/bin/env node
// One-off: download the faction emblems (SVG) used as chip logos in the filter.
// Saves to public/factions/<slug>.<ext> (served by URL, not bundled) and writes
// src/data/factionLogos.js mapping the affiliation id → file.

import { promises as fs } from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { fetchPage, resolveImage, download } from './lib/wookiee.mjs'

const ROOT = path.resolve(fileURLToPath(import.meta.url), '..', '..')
const OUT_DIR = path.join(ROOT, 'public', 'factions')

// Affiliation id (as stored in planets.json) → Wookieepedia page title.
const FACTIONS = [
  'Galactic Empire',
  'Galactic Republic',
  'New Republic',
  'Confederacy of Independent Systems',
  'Alliance to Restore the Republic',
  'First Order',
  'Sith Empire',
  'Jedi Order',
]

const slug = (s) => s.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '')
const extFromMime = (m) =>
  ({ 'image/svg+xml': 'svg', 'image/png': 'png', 'image/jpeg': 'jpg', 'image/webp': 'webp' }[m] || 'png')

async function main() {
  await fs.mkdir(OUT_DIR, { recursive: true })
  const map = {}
  for (const id of FACTIONS) {
    try {
      const page = await fetchPage(id)
      const lead = (page.wikitext || '').split(/\n==/)[0]
      const m = /(?:File:)?\s*([^[\]|{}=]+?\.(?:png|jpg|jpeg|svg|webp))/i.exec(lead)
      if (!m) { console.log(id, '· no image'); continue }
      const info = await resolveImage(m[1].trim().replace(/ /g, '_'))
      if (!info) { console.log(id, '· unresolved'); continue }
      const ext = extFromMime(info.mime)
      const file = `${slug(id)}.${ext}`
      const buf = await download(info.url)
      await fs.writeFile(path.join(OUT_DIR, file), buf)
      map[id] = file
      console.log(id.padEnd(38), '→', file, `(${(buf.length / 1024).toFixed(0)} kB)`)
    } catch (e) {
      console.log(id, '· ERR', e.message)
    }
  }
  const js =
    '// AUTO-GENERATED by scripts/fetch-faction-logos.mjs — faction emblem lookup.\n' +
    `const FILES = ${JSON.stringify(map, null, 2)}\n\n` +
    'export const factionLogo = (id) =>\n' +
    "  FILES[id] ? `${process.env.PUBLIC_URL || ''}/factions/${FILES[id]}` : null\n"
  await fs.writeFile(path.join(ROOT, 'src', 'data', 'factionLogos.js'), js)
  console.log(`\nwrote src/data/factionLogos.js (${Object.keys(map).length} logos)`)
}
main()
